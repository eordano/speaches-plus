cudaLibrary_t g_libs[CFX_SHAPES] = {};
cudaKernel_t g_kernels[CFX_SHAPES] = {};

int shape_index(int m, int n, int k) {
    for (int i = 0; i < CFX_SHAPES; i++)
        if (g_shapes[i].m == m && g_shapes[i].n == n && g_shapes[i].k == k)
            return i;
    return -1;
}

struct alignas(64) CfxTensorMapParam {
    unsigned char bytes[128];
};

}

extern "C" int nv_kernels_nvfp4_cfx_shape_index(int m, int n, int k) {
    return shape_index(m, n, k);
}

extern "C" int nv_kernels_nvfp4_cfx_load(const void* cubin, size_t cubin_bytes,
                                         int m, int n, int k) {
    int idx = shape_index(m, n, k);
    if (idx < 0) return -100;
    if (g_kernels[idx]) return 0;
    cudaError_t e = cudaLibraryLoadData(&g_libs[idx], cubin, nullptr, nullptr,
                                        0, nullptr, nullptr, 0);
    if (e != cudaSuccess) return (int)e;
    e = cudaLibraryGetKernel(&g_kernels[idx], g_libs[idx], g_shapes[idx].sym);
    if (e != cudaSuccess) {
        g_kernels[idx] = nullptr;
        return (int)e;
    }
    int dev = 0;
    cudaGetDevice(&dev);
    e = cudaKernelSetAttributeForDevice(
        g_kernels[idx], cudaFuncAttributeMaxDynamicSharedMemorySize,
        (int)CFX_DYN_SMEM_BYTES_FROM_CAPTURED_DSL_LAUNCH, dev);
    return (e == cudaSuccess) ? 0 : (int)e;
}

extern "C" int nv_kernels_nvfp4_cfx_ready(int m, int n, int k) {
    int idx = shape_index(m, n, k);
    return (idx >= 0 && g_kernels[idx]) ? 1 : 0;
}

extern "C" int nv_kernels_nvfp4_cfx_gemm_bf16(
    void* stream,
    const void* a_fp4,
    const void* a_sf96,
    const void* b_fp4,
    const void* b_sf128,
    const float* alpha_dev,
    void* d_bf16,
    int m,
    int n,
    int k
) {
    int idx = shape_index(m, n, k);
    if (idx < 0) return -100;
    if (!g_kernels[idx]) return -101;
    const void* bases[5] = {a_fp4, b_fp4, a_sf96, b_sf128, d_bf16};
    CfxTensorMapParam maps[5];
    for (int t = 0; t < 5; t++) {
        memset(maps[t].bytes, 0, 128);
        memcpy(maps[t].bytes, g_shapes[idx].maps[t], 64);
        memcpy(maps[t].bytes, &bases[t], 8);
    }
    unsigned char sched_param_unread_by_kernel[16] = {};
    const float* alpha = alpha_dev;
    void* params[7] = {&maps[0], &maps[1], &maps[2], &maps[3], &maps[4],
                       sched_param_unread_by_kernel, &alpha};
    cudaLaunchConfig_t cfg = {};
    cfg.gridDim = dim3(1, 1, CFX_GRID_Z_PERSISTENT_ONE_CTA_PER_SM120_SM);
    cfg.blockDim = dim3(CFX_BLOCK_THREADS_16_WARPS, 1, 1);
    cfg.dynamicSmemBytes = CFX_DYN_SMEM_BYTES_FROM_CAPTURED_DSL_LAUNCH;
    cfg.stream = static_cast<cudaStream_t>(stream);
    cudaError_t e =
        cudaLaunchKernelExC(&cfg, (const void*)g_kernels[idx], params);
    return (e == cudaSuccess) ? 0 : (int)e;
}
